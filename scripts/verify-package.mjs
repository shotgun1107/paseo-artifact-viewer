import assert from "node:assert/strict";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { metadata, output, readRelease, startServerFixture } from "../test/browser-server.mjs";

const release = readRelease();
const fixture = await startServerFixture(release);
const sessionId = "qa-verify";
const handlers = [...fixture.handlers.keys()].sort();
const hooks = [...fixture.hooks.keys()].sort();
try {
  assert.deepEqual(handlers, ["artifact.backfill", "artifact.card_placements", "artifact.card_placements_changed", "artifact.failed_notices", "artifact.get", "artifact.history", "artifact.library_get", "artifact.library_list", "artifact.list", "artifact.manage", "artifact.open", "artifact.restore_version", "artifact.save_edit", "artifact.set_locale", "artifact.sidebar_ack", "artifact.sidebar_pending", "artifact.sidebar_refresh_requests", "artifact.sidebar_requests"]);
  assert.deepEqual(hooks, ["agent.create.before", "agent.open.before", "agent.turn.after", "agent.turn.before"]);
  const context = { paseo: fixture.paseo };
  const agent = { id: sessionId, provider: "codex", cwd: "C:/fixture" };
  const create = fixture.hooks.get("agent.create.before");
  const created = await create({ request: { config: { provider: agent.provider, cwd: agent.cwd } } }, context);
  for (const toolName of ["artifact_publish", "artifact_list", "artifact_read", "artifact_open"]) assert.ok(created.config.systemPrompt.includes(toolName), toolName);
  assert.match(created.config.systemPrompt, /When the user asks for an artifact/);
  assert.deepEqual(await fixture.rpc("artifact.set_locale", { locale: "ko-KR" }), { locale: "ko" });
  assert.equal(await create({ request: created }, context), undefined);
  const korean = await create({ request: { config: { provider: agent.provider, cwd: agent.cwd } } }, context);
  assert.match(korean.config.systemPrompt, /사용자가 아티팩트를 요청/);
  assert.equal(await create({ request: korean }, context), undefined);
  const open = fixture.hooks.get("agent.open.before")({ request: { agentId: sessionId, provider: agent.provider, purpose: "interactive", tools: [], mcpServers: {} } }, context);
  const publish = open.tools.find(tool => tool.name === "artifact_publish");
  assert.equal(publish.title, "아티팩트 발행");
  const content = "<h1>Packaged artifact</h1>";
  const result = await publish.execute({ requestId: "package-smoke", key: "qa", kind: "html", content, title: "QA" }, { ...context, agent, signal: new AbortController().signal });
  assert.equal(result.structuredContent.status, "ok");
  assert.equal(result.structuredContent.sidebar, "closed");
  const { artifactId } = result.structuredContent;
  const library = await fixture.rpc("artifact.library_list", { query: "QA" });
  assert.deepEqual(library.items.map(item => [item.artifactId, item.headVersion]), [[artifactId, 1]]);
  assert.equal("content" in library.items[0], false);
  assert.equal((await fixture.rpc("artifact.library_get", { artifactId })).version.content, content);
  const edit = { sessionId, artifactId, baseVersion: 1, content: "<h2>QA edit</h2>", clientMutationId: "edit-1" };
  const saved = await fixture.rpc("artifact.save_edit", edit);
  assert.equal(saved.version, 2);
  assert.deepEqual(await fixture.rpc("artifact.save_edit", edit), saved);
  assert.equal((await fixture.rpc("artifact.save_edit", { ...edit, clientMutationId: "conflicting-edit" })).status, "conflict");
  const react = await publish.execute({ requestId: "package-react", key: "tsx-test", kind: "react", title: "TSX", content: "export default function App(){const value: number = 7;return <h1>{value}</h1>}" }, { ...context, agent, signal: new AbortController().signal });
  const web = await fixture.rpc("artifact.manage", { sessionId, artifactId: react.structuredContent.artifactId, action: { type: "web", version: 1 } });
  assert.equal(new URL(web.url).hostname, "127.0.0.1");
  const response = await fetch(web.url);
  assert.ok(response.ok);
  const document = await response.text();
  assert.match(document, /importmap/);
  assert.match(document, /__avReact.createElement/);
  assert.doesNotMatch(document, /value: number/);
  await fixture.restart();
  const afterRestart = await fixture.hooks.get("agent.create.before")({ request: { config: { provider: agent.provider, cwd: agent.cwd } } }, context);
  assert.equal(afterRestart.config.systemPrompt, korean.config.systemPrompt);
  assert.equal((await fixture.rpc("artifact.get", { sessionId, artifactId })).version.content, edit.content);
  assert.equal((await fixture.rpc("artifact.get", { sessionId, artifactId, version: 1 })).version.content, content);
  assert.equal(await fixture.rpc("artifact.get", { sessionId: "other-session", artifactId }), null);
  assert.deepEqual((await fixture.rpc("artifact.history", { sessionId, artifactId })).items.map(x => x.version), [2, 1]);
  const request = { sessionId, artifactId, version: 1, baseVersion: 2, clientMutationId: "restore-old-version" };
  const restored = await fixture.rpc("artifact.restore_version", request);
  assert.equal(restored.version, 3);
  assert.deepEqual(await fixture.rpc("artifact.restore_version", request), restored);
  const newHead = (await fixture.rpc("artifact.get", { sessionId, artifactId })).version;
  assert.equal(newHead.content, content);
  assert.equal(newHead.origin.restoredFromVersion, 1);

} finally { await fixture.close(); }
const report = { version: metadata.version, archiveSha256: release.sha256, archiveEntries: release.entries, node: process.versions.node, sqlite: process.versions.sqlite, handlers, hooks, hookCleanup: fixture.hooks.size === 0, checks: ["English and Korean guide injection and mixed-language replay", "daemon locale persistence", "Codex tool publication", "host library summary and detail", "save and retry", "stale edit conflict", "SQLite reopen and history", "restore historical source and retry", "session isolation", "packaged Sucrase TSX transformation via loopback web RPC"], scope: "Packaged server entry and SDK lifecycle adapter in an isolated Node process" };
assert.ok(report.hookCleanup);
writeFileSync(join(output, "package-server-verification.json"), JSON.stringify(report, null, 2) + "\n");
console.log(JSON.stringify(report, null, 2));
